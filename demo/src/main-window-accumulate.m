#define _GNU_SOURCE

#import "import.h"

#include <math.h>


/*
 * stolen from: https://editor.p5js.org/p5/sketches/Interaction:_Wavemaker
 *
 * @name Wavemaker
 * @description This illustrates how waves (like water waves) emerge
 * from particles oscillating in place. Move your mouse to direct the wave.
 * Contributed by Aatish Bhatia, inspired by <a href="https://beesandbombs.tumblr.com/post/45513650541/orbiters">Orbiters</a> by Dave Whyte.
 */

static void   draw( CALayer *layer, CGContext *context)
{
   CGFloat   x, y;
   CGFloat   xAngle;
   CGFloat   yAngle;
   CGFloat   angle;
   CGFloat   myX;
   CGFloat   myY;
   CGFloat   t;
   CGPoint   mouse;
   CGRect    canvas;

   canvas = [layer canvas];
   [context fillRect:canvas
            hexColor:CGHexColorMakeWithColor( CGColorMakeWithGrayABytes( 20, 20))];

   mouse = [context mouseLocation];
   t     = [context secondsSinceFirstRender];

     // make a x and y grid of ellipses
   for( x = 0; x <= canvas.size.width; x = x + 30)
   {
      for( y = 0; y <= canvas.size.height; y = y + 30)
      {
         // starting point of each circle depends on mouse position
         xAngle = CGFloatProjectClamped( mouse.x, 0, canvas.size.width, -4 * M_PI, 4 * M_PI);
         yAngle = CGFloatProjectClamped( mouse.y, 0, canvas.size.height, -4 * M_PI, 4 * M_PI);
         // and also varies based on the particle's location
         angle = xAngle * (x / canvas.size.width) + yAngle * (y / canvas.size.height);

         // each particle moves in a circle
         myX = x + 20 * cosf( 2 * M_PI * t + angle);
         myY = y + 20 * sin( 2 * M_PI * t + angle);

         [context fillCircleAtPoint:CGPointMake( myX, myY)
                             radius:5.0
                           hexColor:CGHexColorMakeWithColor( CGColorMakeWithRGBBytes( 20, 200, 20))];
      }
   }
}



int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;

   app = [UIApplication sharedInstance];
   {
      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 600.0, 600.0)
                         titleUTF8String:"Demo"
                               styleMask:UIWindowStyleMaskDefault];
      // prevent framebuffer from being destroyed
      [window setOpaque:YES];

      [window setBackgroundColor:CGColorMakeGreen()];
      [window setDrawCallback:(CALayerDrawCallback_t *) draw];
      [window setFrameRateHz:60.0];
      [UIApp addWindow:window];
   }
   return( [app run]);
}



